const catalogs: Record<AppLocale, Record<MessageKey, string>> = { 'zh-TW': zhTW, en };

export function translate(locale: AppLocale, key: MessageKey, values: MessageValues = {}): string {
  const template = catalogs[locale][key];
  return template.replace(/\{([a-zA-Z0-9_]+)\}/g, (_match, name: string) =>
    Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : `{${name}}`,
  );
}

export function localeForIntl(locale: AppLocale): string {
  return locale === 'en' ? 'en-US' : 'zh-TW';
}

export function formatNumber(locale: AppLocale, value: number): string {
  return value.toLocaleString(localeForIntl(locale));
}

export function applyDocumentLocale(document: Document, locale: AppLocale): void {
  document.documentElement.lang = locale === 'en' ? 'en' : 'zh-Hant-TW';
  document.documentElement.dataset.locale = locale;
  document.documentElement.dir = 'ltr';
}

